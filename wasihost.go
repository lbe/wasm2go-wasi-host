// Package wasihost implements a WASI snapshot-preview1 host for Go code
// produced by [wasm2go]. It implements all 40 WASI Preview1 imports plus
// the env.call_host_function stub used by some wasm2go modules.
//
// The guest sees only preopened directories. Each preopen is a read-only
// [fs.FS] mount or a writable host directory, with one backend. To give a
// guest both embedded and host data, use separate preopens. See
// ARCHITECTURE.md for the source layout and syscall flow.
//
// The package runs on Linux, macOS, Windows and FreeBSD. README.md lists the
// limitations on each OS.
//
// # Usage
//
// Construct a [State] with [New], passing a callback that returns the guest's
// linear memory slice. The host calls it on every syscall, so it sees memory
// after the guest grows it:
//
//	cfg := wasihost.NewModuleConfig().
//	    WithArgs("app").
//	    WithHostDirectoryPreopen("/", hostDir)
//	state := wasihost.New(func() []byte { return *mod.Xmemory().Slice() }, cfg)
//	mod := generated.New(state, state)
//
// Recover [ExitError] at the module boundary to obtain the guest exit code.
//
// # Concurrency
//
// [State] is not safe for concurrent use. Each wasm2go module instance needs
// its own State, used from a single goroutine.
//
// # Memory layout
//
// All multi-byte integers written into guest memory are little-endian per the
// WASI snapshot-preview1 specification.
package wasihost

import (
	"encoding/binary"
	"fmt"
	"runtime"
	"strconv"
	"strings"
	"sync"

	"github.com/lbe/wasm2go-wasi-host/internal/wasi"
)

// State is a WASI snapshot-preview1 host for a single wasm2go Module
// instance. It implements all X-prefixed method interfaces generated by
// wasm2go for the wasi_snapshot_preview1 and env import modules.
//
// Construct State with [New]; do not create it directly.
// State is not safe for concurrent use.
type State struct {
	mem         func() []byte
	ctx         *wasi.Context
	trace       bool
	assertOwner bool
	ownerMu     sync.Mutex
	ownerGID    uint64
}

// ExitError is the panic value raised by proc_exit. Embedding applications
// must recover it at the wasm eval boundary to obtain the guest exit code:
//
//	defer func() {
//	    if r := recover(); r != nil {
//	        if e, ok := r.(wasihost.ExitError); ok {
//	            // e.Code is the guest exit status
//	        }
//	    }
//	}()
type ExitError struct{ Code int32 }

// Error implements the error interface. Returns a string of the form
// "exit status N" where N is the guest exit code.
func (e ExitError) Error() string { return fmt.Sprintf("exit status %d", e.Code) }

// New creates a WASI snapshot-preview1 host state. mem is called on every
// syscall invocation to obtain the current guest linear memory slice; it is
// safe to call after memory growth events because wasm2go re-slices on grow.
//
// The returned *State satisfies the X-prefixed method interfaces generated
// by wasm2go. Pass it as both import arguments to the generated module's
// New constructor:
//
//	state := wasihost.New(func() []byte { return *mod.Xmemory().Slice() }, cfg)
//	mod   := generated.New(state, state)
//
// If mem is nil, any method that accesses guest memory will panic. A nil
// mem is only safe for tests that do not exercise memory-reading methods.
func New(mem func() []byte, config *ModuleConfig) *State {
	if config == nil {
		config = NewModuleConfig().WithSysWalltime().WithSysNanotime().WithSysNanosleep()
	}
	s := &State{mem: mem}
	s.applyModuleConfig(config)
	return s
}

// Mem returns the current guest linear memory slice by invoking the mem
// callback passed to [New]. The returned slice may be replaced after any
// memory growth event; callers must not retain it across calls.
func (s *State) Mem() []byte { return s.mem() }

// lookupFD resolves fd through ctx.FSContext().LookupFile.
func (s *State) lookupFD(fd int32) (*wasi.FileEntry, bool) {
	if s.ctx == nil {
		return nil, false
	}
	fsc := s.ctx.FSContext()
	if fsc == nil {
		return nil, false
	}
	return fsc.LookupFile(fd)
}

func (s *State) abortPathOpenFD(fd int32) {
	if s.ctx != nil && s.ctx.FSContext() != nil {
		_ = s.ctx.FSContext().CloseFile(fd)
	}
}

// pathOpenStoredGuestPath returns the guest-absolute path for an opened fd.
func (s *State) pathOpenStoredGuestPath(preopen *PreopenEntry, relPath, guestPath string, dirfd int32) string {
	if fe, ok := s.lookupFD(dirfd); ok && fe.IsPreopen {
		return preopenGuestPathForRel(preopen, relPath)
	}
	fe, _ := s.lookupFD(dirfd)
	return s.guestAbsPathForFE(dirfd, guestPath, fe)
}

func (s *State) writeGuestFD(fd, fdPtr int32) {
	binary.LittleEndian.PutUint32(s.mem()[fdPtr:], uint32(fd))
}

// bridgePathOpenFD records rights and guest path on a FileEntry opened via FSContext.OpenFile.
func (s *State) bridgePathOpenFD(fd int32, preopen *PreopenEntry, relPath, guestPath string, dirfd int32, parentBase, parentInh uint64, fdRightsBase, fdRightsInheriting int64, fdFlags int32, fdPtr int32) int32 {
	fe, ok := s.lookupFD(fd)
	if !ok || fe == nil || fe.File == nil {
		s.abortPathOpenFD(fd)
		return wasiEBadf
	}
	st, werrno := fe.File.Stat()
	if werrno != 0 {
		s.abortPathOpenFD(fd)
		return errnoFromWasi(werrno)
	}
	fdType := filestatFdTypeFromMode(st.Mode)
	rb, ri := pathOpenStoredRights(parentBase, parentInh, fdType, fdRightsBase, fdRightsInheriting)
	fe.RightsBase = rb
	fe.RightsInheriting = ri
	fe.FdFlags = uint16(fdFlags)
	fe.GuestPath = s.pathOpenStoredGuestPath(preopen, relPath, guestPath, dirfd)
	if fdFlags&fdFlagsAppend != 0 {
		_ = fe.File.SetAppend(true)
	}
	if pf, ok := fe.File.(wasi.PollableFile); ok && fdFlags&fdFlagsNonBlock != 0 {
		_ = pf.SetNonblock(true)
	}
	s.writeGuestFD(fd, fdPtr)
	return wasiESuccess
}

// logTrace writes a formatted line to os.Stdout when tracing is enabled.
func (s *State) logTrace(format string, args ...interface{}) {
	if s.trace {
		fmt.Printf(format+"\n", args...)
	}
}

// assertSingleOwner panics if the calling goroutine is not the goroutine
// that first called a method on this State. Has no effect when owner
// assertion is disabled on this State.
func (s *State) assertSingleOwner() {
	if !s.assertOwner {
		return
	}
	gid := currentGID()
	s.ownerMu.Lock()
	defer s.ownerMu.Unlock()
	if s.ownerGID == 0 {
		s.ownerGID = gid
		return
	}
	if s.ownerGID != gid {
		panic(fmt.Sprintf("wasiState single-owner invariant violated: owner goroutine=%d current goroutine=%d", s.ownerGID, gid))
	}
}

// currentGID returns the numeric ID of the calling goroutine by parsing
// the output of runtime.Stack. There is no public Go API for goroutine IDs;
// this approach is fragile. Only debugging assertions use it.
func currentGID() uint64 {
	var b [64]byte
	n := runtime.Stack(b[:], false)
	line := string(b[:n])
	const prefix = "goroutine "
	if !strings.HasPrefix(line, prefix) {
		panic("unable to parse goroutine id: missing prefix")
	}
	line = line[len(prefix):]
	end := strings.IndexByte(line, ' ')
	if end < 0 {
		panic("unable to parse goroutine id: missing delimiter")
	}
	id, err := strconv.ParseUint(line[:end], 10, 64)
	if err != nil {
		panic(fmt.Sprintf("unable to parse goroutine id: %v", err))
	}
	return id
}
